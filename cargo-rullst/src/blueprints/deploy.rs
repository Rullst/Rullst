//! The files `cargo rullst deploy` writes next to the Dockerfile.

/// Address the generated Caddy proxy holds on the compose `edge` network.
/// `cargo rullst deploy` lists it in `Rullst.toml` `[security]
/// trusted_proxies`, so the app reads each client from `X-Forwarded-For`
/// instead of seeing every request come from Caddy.
pub const VPS_PROXY_ADDRESS: &str = "172.31.250.10";

/// The app and a Caddy reverse proxy for one Linux VM, for `docker compose`
/// and `podman compose`: read-only root filesystems, every capability
/// dropped (Caddy keeps only `NET_BIND_SERVICE` for ports 80/443), no new
/// privileges, and a health check of the app's `/health` endpoint.
pub const COMPOSE_YAML: &str = r#"# Generated by `cargo rullst deploy`: the app and a Caddy reverse proxy with
# automatic HTTPS, for one Linux VM with Docker or Podman.
#
#   DOMAIN=example.com docker compose up -d --build
#   DOMAIN=example.com podman compose up -d --build
#
# Production settings (APP_KEY, DATABASE_URL, provider keys...) go in
# .env.production next to this file; .gitignore and .dockerignore keep it out
# of Git and of the image. This file is yours: edit it freely.

services:
  app:
    build: .
    restart: unless-stopped
    env_file:
      - .env.production
    environment:
      RULLST_ENV: production
      HOST: 0.0.0.0
      PORT: "3000"
    expose:
      - "3000"
    # The image runs as an unprivileged user without a shell; it writes only
    # to the data volume and /tmp.
    read_only: true
    tmpfs:
      - /tmp
    volumes:
      - app_data:/app/data
    cap_drop:
      - ALL
    security_opt:
      - no-new-privileges:true
    networks:
      - edge

  caddy:
    image: docker.io/library/caddy:2-alpine
    restart: unless-stopped
    depends_on:
      - app
    ports:
      - "80:80"
      - "443:443"
      - "443:443/udp"
    environment:
      DOMAIN: ${DOMAIN:-localhost}
    volumes:
      - ./Caddyfile:/etc/caddy/Caddyfile:ro
      - caddy_data:/data
      - caddy_config:/config
    read_only: true
    tmpfs:
      - /tmp
    cap_drop:
      - ALL
    # Only to listen on ports 80 and 443 inside the container.
    cap_add:
      - NET_BIND_SERVICE
    security_opt:
      - no-new-privileges:true
    # The app image has no shell or HTTP client, so its /health endpoint is
    # probed from this container (the Caddyfile also checks it).
    healthcheck:
      test: ["CMD", "wget", "-q", "-O", "/dev/null", "http://app:3000/health"]
      interval: 30s
      timeout: 5s
      retries: 3
      start_period: 30s
    networks:
      edge:
        # Rullst.toml [security] trusted_proxies trusts only this address to
        # report the client address. Change both together.
        ipv4_address: 172.31.250.10

networks:
  edge:
    ipam:
      config:
        # Pinned so the proxy address is known. If it overlaps a network on
        # this host, choose another private /24 and update the address above.
        - subnet: 172.31.250.0/24

volumes:
  app_data:
  caddy_data:
  caddy_config:
"#;

/// Caddy (2.5+) replaces a client-supplied `X-Forwarded-For` with the address
/// it received the request from, which the app trusts from this proxy only.
pub const CADDYFILE: &str = r#"# Generated by `cargo rullst deploy`. DOMAIN comes from compose.yaml; Caddy
# obtains and renews the HTTPS certificate for it automatically.
{$DOMAIN:localhost} {
    reverse_proxy app:3000 {
        # Stop routing to the app while /health fails.
        health_uri /health
        health_interval 30s
    }
}
"#;

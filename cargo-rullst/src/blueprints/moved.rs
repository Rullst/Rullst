// src/blueprints/moved.rs — Blueprints that left `cargo rullst new` in
// 13.0.0-alpha.4. LMS and Blog live on as complete applications under
// `examples/`; the Portfolio and ERP examples were removed in 13.0.0-alpha.5,
// and the blog example, which shows the same CRUD with Nexus, replaces them.

use std::fmt;

/// Where the repository's examples are browsed on GitHub.
const EXAMPLES_URL: &str = "https://github.com/Rullst/Rullst/tree/main/examples";

/// A blueprint removed from `cargo rullst new` in 13.0.0-alpha.4, with the
/// example application of the Rullst repository (`examples/<example>`) that
/// replaces it; asking for it fails before anything is written.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct MovedBlueprint {
    name: &'static str,
    example: &'static str,
}

impl MovedBlueprint {
    /// The LMS starter, now `examples/lms`.
    pub const LMS: Self = Self {
        name: "lms",
        example: "lms",
    };
    /// The Blog starter; `examples/blog` is the blog showcase that replaces it.
    pub const BLOG: Self = Self {
        name: "blog",
        example: "blog",
    };
    /// The Portfolio starter. Its example was removed in 13.0.0-alpha.5;
    /// `examples/blog` shows the same Nexus-edited pages.
    pub const PORTFOLIO: Self = Self {
        name: "portfolio",
        example: "blog",
    };
    /// The ERP starter. Its example was removed in 13.0.0-alpha.5;
    /// `examples/blog` shows the same CRUD behind Nexus.
    pub const ERP: Self = Self {
        name: "erp",
        example: "blog",
    };

    /// The removed blueprints with their former IDs, which are never reused.
    const RETIRED: [(usize, Self); 4] = [
        (1, Self::LMS),
        (3, Self::BLOG),
        (4, Self::PORTFOLIO),
        (5, Self::ERP),
    ];

    /// The moved blueprint called `name` (its former `--blueprint` value).
    pub fn from_name(name: &str) -> Option<Self> {
        Self::RETIRED
            .iter()
            .find(|(_, moved)| moved.name == name)
            .map(|(_, moved)| *moved)
    }

    /// The moved blueprint that had the stable ID `id`.
    pub fn from_id(id: usize) -> Option<Self> {
        Self::RETIRED
            .iter()
            .find(|(retired, _)| *retired == id)
            .map(|(_, moved)| *moved)
    }

    /// The former `--blueprint` value.
    pub const fn name(self) -> &'static str {
        self.name
    }

    /// Whether the example that once held this starter's code was removed
    /// (Portfolio and ERP, in 13.0.0-alpha.5), so another example replaces it.
    pub fn example_removed(self) -> bool {
        self.name != self.example
    }

    /// The replacing example's directory in the Rullst repository.
    pub fn directory(self) -> String {
        format!("examples/{}", self.example)
    }

    /// The replacing example on GitHub.
    pub fn url(self) -> String {
        format!("{EXAMPLES_URL}/{}", self.example)
    }
}

impl fmt::Display for MovedBlueprint {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        if self.example_removed() {
            return write!(
                formatter,
                "the `{}` blueprint is no longer generated by `cargo rullst new` (removed in 13.0.0-alpha.4), \
                 and its example application was removed in 13.0.0-alpha.5; {} of the Rullst repository \
                 shows the same CRUD with a Nexus back office: {}",
                self.name,
                self.directory(),
                self.url()
            );
        }
        write!(
            formatter,
            "the `{}` blueprint is no longer generated by `cargo rullst new` (removed in 13.0.0-alpha.4); \
             it is now the example application in {} of the Rullst repository: {}",
            self.name,
            self.directory(),
            self.url()
        )
    }
}

impl std::error::Error for MovedBlueprint {}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn each_moved_blueprint_names_the_example_that_replaces_it() {
        for (id, name, example) in [
            (1, "lms", "lms"),
            (3, "blog", "blog"),
            (4, "portfolio", "blog"),
            (5, "erp", "blog"),
        ] {
            let by_name = MovedBlueprint::from_name(name).expect("a moved blueprint");
            assert_eq!(MovedBlueprint::from_id(id), Some(by_name));
            assert_eq!(by_name.name(), name);
            assert_eq!(by_name.example_removed(), name != example, "{name}");
            assert_eq!(by_name.directory(), format!("examples/{example}"));
            assert_eq!(
                by_name.url(),
                format!("https://github.com/Rullst/Rullst/tree/main/examples/{example}")
            );
        }
        let lms = MovedBlueprint::from_name("lms").expect("lms");
        assert_eq!(
            lms.to_string(),
            "the `lms` blueprint is no longer generated by `cargo rullst new` (removed in 13.0.0-alpha.4); \
             it is now the example application in examples/lms of the Rullst repository: \
             https://github.com/Rullst/Rullst/tree/main/examples/lms"
        );
        assert_eq!(
            MovedBlueprint::ERP.to_string(),
            "the `erp` blueprint is no longer generated by `cargo rullst new` (removed in 13.0.0-alpha.4), \
             and its example application was removed in 13.0.0-alpha.5; examples/blog of the Rullst \
             repository shows the same CRUD with a Nexus back office: \
             https://github.com/Rullst/Rullst/tree/main/examples/blog"
        );
    }

    #[test]
    fn current_starters_and_unknown_values_are_not_moved() {
        for name in ["blank", "api", "saas", "uptime", ""] {
            assert_eq!(MovedBlueprint::from_name(name), None, "{name}");
        }
        for id in [0, 2, 6, usize::MAX] {
            assert_eq!(MovedBlueprint::from_id(id), None, "{id}");
        }
    }
}

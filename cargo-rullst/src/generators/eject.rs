use colored::Colorize;
use std::fs;
use std::io::{self, ErrorKind, Write};
use std::path::{Component, Path, PathBuf};

/// The entry point written by `cargo rullst eject`.
///
/// It is a template, not a translation of the project's `main.rs`: Axum is
/// reached through the `rullst::web` re-export (generated projects do not
/// depend on it directly), and the configured Rullst security baseline wraps
/// the placeholder routes exactly as `Server` applies it.
const EJECTED_ENTRY_POINT: &str = r#"// ==========================================================================
// EJECTED ENTRY POINT — reviewable Axum & Tokio starting point
// Generated by 'cargo rullst eject'
//
// This is a template, not a translation of the previous entry point: move the
// application's routes into `application_routes()` (after `--force`, the
// original is kept in src/main.rs.rullst-backup). `apply_security_baseline`
// installs the configured secure headers, CORS, WAF/RASP and CSRF layers
// (headers, WAF and CSRF apply in staging/production) from Rullst.toml, as
// `rullst::Server` does. Static files, rate limiting, lifecycle probes, hot
// reload, sessions, authentication and authorization are not included.
// ==========================================================================

use rullst::RullstConfig;
use rullst::web::axum::{Router, response::Html, routing::get};
use std::net::SocketAddr;

/// Mount the application's routes here.
fn application_routes() -> Router {
    Router::new().route("/", get(|| async { Html("<h1>Ejected Axum Server</h1>") }))
}

#[rullst::runtime::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    let config = if std::path::Path::new("Rullst.toml").exists() {
        RullstConfig::load_from_file("Rullst.toml").await?
    } else {
        RullstConfig::default()
    };
    let environment = config.environment()?;
    let app = rullst::apply_security_baseline(application_routes(), config.security, environment)?;

    let addr = SocketAddr::from(([127, 0, 0, 1], 3000));
    println!("Ejected server listening on http://{addr}");
    let listener = rullst::async_runtime::tokio::net::TcpListener::bind(addr).await?;
    rullst::web::axum::serve(
        listener,
        app.into_make_service_with_connect_info::<SocketAddr>(),
    )
    .await?;
    Ok(())
}
"#;

/// Returns the exact entry point written by `cargo rullst eject`.
///
/// Public so scaffold smoke tests can compile the generated source.
#[doc(hidden)]
pub fn ejected_entry_point_source() -> &'static str {
    EJECTED_ENTRY_POINT
}

fn resolve_target(force: bool, output_path: Option<&str>) -> Result<PathBuf, io::Error> {
    let target = PathBuf::from(output_path.unwrap_or(if force {
        "src/main.rs"
    } else {
        "src/ejected_main.rs"
    }));
    if target.is_absolute()
        || target.extension().and_then(|extension| extension.to_str()) != Some("rs")
        || target
            .components()
            .any(|component| !matches!(component, Component::Normal(_)))
        || target.components().next() != Some(Component::Normal("src".as_ref()))
    {
        return Err(io::Error::new(
            ErrorKind::InvalidInput,
            "eject output must be a relative Rust file below src/",
        ));
    }
    if target == Path::new("src/main.rs") && !force {
        return Err(io::Error::new(
            ErrorKind::PermissionDenied,
            "overwriting src/main.rs requires --force",
        ));
    }

    let source_root = fs::canonicalize("src")?;
    let parent = target.parent().ok_or_else(|| {
        io::Error::new(
            ErrorKind::InvalidInput,
            "eject output has no parent directory",
        )
    })?;
    let canonical_parent = fs::canonicalize(parent)?;
    if !canonical_parent.starts_with(source_root) {
        return Err(io::Error::new(
            ErrorKind::InvalidInput,
            "eject output resolves outside src/",
        ));
    }
    Ok(target)
}

fn preserve_backup(source: &Path, backup: &Path) -> Result<(), io::Error> {
    let mut input = fs::File::open(source)?;
    let mut output = fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(backup)
        .map_err(|error| {
            if error.kind() == ErrorKind::AlreadyExists {
                io::Error::new(
                    ErrorKind::AlreadyExists,
                    format!(
                        "backup '{}' already exists; move or review it before --force",
                        backup.display()
                    ),
                )
            } else {
                error
            }
        })?;
    if let Err(error) = io::copy(&mut input, &mut output) {
        drop(output);
        let _ = fs::remove_file(backup);
        return Err(error);
    }
    Ok(())
}

fn write_new_file(path: &Path, contents: &[u8]) -> Result<(), io::Error> {
    let mut output = fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)
        .map_err(|error| {
            if error.kind() == ErrorKind::AlreadyExists {
                io::Error::new(
                    ErrorKind::AlreadyExists,
                    format!(
                        "refusing to overwrite existing eject output '{}'",
                        path.display()
                    ),
                )
            } else {
                error
            }
        })?;
    if let Err(error) = output.write_all(contents) {
        drop(output);
        let _ = fs::remove_file(path);
        return Err(error);
    }
    Ok(())
}

pub fn run_eject_project(
    force: bool,
    output_path: Option<&str>,
) -> Result<(), Box<dyn std::error::Error>> {
    println!(
        "{}",
        "🚪 Generating a reviewable Axum/Tokio entry-point template..."
            .bright_cyan()
            .bold()
    );

    let target_file = resolve_target(force, output_path)?;
    let main_rs_path = Path::new("src/main.rs");

    if !main_rs_path.exists() {
        println!(
            "{}",
            "❌ Error: src/main.rs not found in current directory.".red()
        );
        return Err(io::Error::new(ErrorKind::NotFound, "src/main.rs not found").into());
    }

    if fs::symlink_metadata(main_rs_path)?.file_type().is_symlink() {
        return Err(io::Error::new(
            ErrorKind::InvalidInput,
            "refusing to replace a symlinked src/main.rs",
        )
        .into());
    }

    let backup = if target_file == main_rs_path {
        let backup = PathBuf::from("src/main.rs.rullst-backup");
        preserve_backup(main_rs_path, &backup)?;
        Some(backup)
    } else {
        None
    };

    if target_file == main_rs_path {
        fs::write(&target_file, EJECTED_ENTRY_POINT)?;
    } else {
        write_new_file(&target_file, EJECTED_ENTRY_POINT.as_bytes())?;
    }

    println!(
        "{}",
        format!(
            "✅ Generated a reviewable Axum/Tokio entry point at '{}'!",
            target_file.display()
        )
        .green()
        .bold()
    );

    if let Some(backup) = backup {
        println!(
            "ℹ️ Original 'src/main.rs' preserved at '{}'.",
            backup.display()
        );
        println!(
            "{}",
            "⚠️ The new entry point does not carry over your routes or module declarations: move them from the backup into application_routes() before deploying."
                .yellow()
        );
    } else {
        println!("ℹ️ Original 'src/main.rs' was not modified.");
    }

    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::tempdir;

    #[test]
    fn eject_target_is_confined_and_force_gated() {
        assert_eq!(
            resolve_target(false, None).unwrap(),
            PathBuf::from("src/ejected_main.rs")
        );
        assert!(resolve_target(false, Some("src/main.rs")).is_err());
        assert_eq!(
            resolve_target(true, Some("src/main.rs")).unwrap(),
            PathBuf::from("src/main.rs")
        );
        for invalid in [
            "../outside.rs",
            "/tmp/outside.rs",
            "Cargo.toml",
            "src/../outside.rs",
        ] {
            assert!(resolve_target(false, Some(invalid)).is_err());
        }
    }

    #[test]
    fn ejected_entry_point_uses_the_facade_and_keeps_the_security_baseline() {
        let source = ejected_entry_point_source();
        assert!(source.contains("use rullst::web::axum::"));
        assert!(source.contains("rullst::web::axum::serve("));
        assert!(source.contains("rullst::apply_security_baseline(application_routes()"));
        assert!(source.contains("into_make_service_with_connect_info::<SocketAddr>()"));
        assert!(!source.contains("use axum::"));
        assert!(!source.contains("\n    axum::"));
        assert!(!source.contains("unwrap("));
        syn::parse_file(source).expect("ejected entry point should parse");
    }

    #[test]
    fn generated_output_and_backup_never_overwrite_existing_files() {
        let directory = tempdir().expect("temporary directory");
        let source = directory.path().join("main.rs");
        let backup = directory.path().join("main.rs.rullst-backup");
        let generated = directory.path().join("ejected_main.rs");
        fs::write(&source, "fn original() {}\n").expect("source fixture");

        preserve_backup(&source, &backup).expect("first backup");
        assert_eq!(
            fs::read_to_string(&backup).expect("backup contents"),
            "fn original() {}\n"
        );
        assert_eq!(
            preserve_backup(&source, &backup)
                .expect_err("backup collision must fail")
                .kind(),
            ErrorKind::AlreadyExists
        );

        write_new_file(&generated, b"fn generated() {}\n").expect("first output");
        assert_eq!(
            write_new_file(&generated, b"fn overwritten() {}\n")
                .expect_err("output collision must fail")
                .kind(),
            ErrorKind::AlreadyExists
        );
        assert_eq!(
            fs::read_to_string(generated).expect("generated contents"),
            "fn generated() {}\n"
        );
    }
}

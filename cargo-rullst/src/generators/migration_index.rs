//! `src/migrations/mod.rs`: the generators keep its migration declarations
//! and `get_migrations()` in step with the migration files, and keep every
//! other item the project wrote there (seed modules, helpers, comments).
use crate::generators::ProjectOrmBackend;
use std::{cmp::Reverse, io, ops::Range};
use syn::spanned::Spanned;

/// The first line the generators wrote before 13.0.0-rc.1, which claimed the
/// whole file.
const LEGACY_HEADER: &str = "// Generated by Rullst. Do not edit manually.";
const HEADER: &str = "// The `pub mod m...;` lines and `get_migrations()` follow the migration files\n// of this directory (`cargo rullst make:migration`); other items are kept.";

/// `src/migrations/mod.rs` registering `modules` (sorted migration module
/// names). An `existing` file keeps every item except its migration
/// declarations and `get_migrations()`, which are regenerated in place.
pub(crate) fn render(
    existing: Option<&str>,
    modules: &[String],
    backend: ProjectOrmBackend,
) -> io::Result<String> {
    let declarations = modules
        .iter()
        .map(|module| format!("pub mod {module};\n"))
        .collect::<String>();
    let function = get_migrations(modules, backend);
    let pending = if declarations.is_empty() {
        String::new()
    } else {
        format!("{declarations}\n")
    };
    let Some(existing) = existing.filter(|source| !source.trim().is_empty()) else {
        return Ok(format!("{HEADER}\n\n{pending}{function}"));
    };
    let file = syn::parse_file(existing).map_err(|error| {
        io::Error::new(
            io::ErrorKind::InvalidData,
            format!(
                "src/migrations/mod.rs is not valid Rust ({error}); it was left unchanged, so register the new migration there by hand"
            ),
        )
    })?;
    let mut edits = Vec::new();
    let mut declared = false;
    let mut function_edit = None;
    for item in &file.items {
        let range = whole_lines(existing, item.span().byte_range());
        match item {
            syn::Item::Mod(module)
                if module.content.is_none() && is_migration(&module.ident, modules) =>
            {
                // Every declaration moves to where the first one was.
                let text = if declared { "" } else { &declarations };
                edits.push((range, text.to_owned()));
                declared = true;
            }
            syn::Item::Fn(item) if item.sig.ident == "get_migrations" => {
                function_edit = Some(range);
            }
            _ => {}
        }
    }
    let pending = if declared { "" } else { pending.as_str() };
    match function_edit {
        Some(range) => edits.push((range, format!("{pending}{function}"))),
        None => {
            let end = existing.len();
            let separator = if existing.ends_with('\n') {
                "\n"
            } else {
                "\n\n"
            };
            edits.push((end..end, format!("{separator}{pending}{function}")));
        }
    }
    edits.sort_by_key(|(range, _)| Reverse(range.start));
    let mut updated = existing.to_owned();
    for (range, text) in edits {
        if updated.get(range.clone()).is_none() {
            return Err(io::Error::other("invalid src/migrations/mod.rs range"));
        }
        updated.replace_range(range, &text);
    }
    if let Some(rest) = updated.strip_prefix(LEGACY_HEADER) {
        updated = format!("{HEADER}{rest}");
    }
    syn::parse_file(&updated).map_err(|error| io::Error::other(error.to_string()))?;
    Ok(updated)
}

/// A declaration the generators own: a migration file of the directory, or
/// a migration whose file is gone (`m` and a digit, as `m<timestamp>_...`).
fn is_migration(ident: &syn::Ident, modules: &[String]) -> bool {
    let name = ident.to_string();
    let mut characters = name.chars();
    modules.contains(&name)
        || (characters.next() == Some('m') && characters.next().is_some_and(|c| c.is_ascii_digit()))
}

/// `range` widened to whole lines when only whitespace shares them, so a
/// removed item leaves no blank remains.
fn whole_lines(source: &str, range: Range<usize>) -> Range<usize> {
    let before = source.get(..range.start).unwrap_or_default();
    let line_start = before.rfind('\n').map_or(0, |at| at + 1);
    let start = if before
        .get(line_start..)
        .unwrap_or_default()
        .trim()
        .is_empty()
    {
        line_start
    } else {
        range.start
    };
    let after = source.get(range.end..).unwrap_or_default();
    let line_end = after
        .find('\n')
        .map_or(source.len(), |at| range.end + at + 1);
    let end = if source
        .get(range.end..line_end)
        .unwrap_or_default()
        .trim()
        .is_empty()
    {
        line_end
    } else {
        range.end
    };
    start..end
}

fn get_migrations(modules: &[String], backend: ProjectOrmBackend) -> String {
    let mut function = String::new();
    match backend {
        ProjectOrmBackend::Sqlx => {
            function.push_str(
                "pub fn get_migrations() -> Vec<Box<dyn rullst::db::schema::Migration>> {\n    vec![\n",
            );
            for module in modules {
                function.push_str(&format!("        Box::new({module}::MigrationImpl),\n"));
            }
            function.push_str("    ]\n}\n");
        }
        ProjectOrmBackend::Turso => {
            function.push_str(
                "pub fn get_migrations() -> Result<\n    Vec<rullst_orm::polyglot::TursoMigration>,\n    rullst_orm::polyglot::PolyglotError,\n> {\n    Ok(vec![\n",
            );
            for module in modules {
                function.push_str(&format!("        {module}::migration()?,\n"));
            }
            function.push_str("    ])\n}\n");
        }
    }
    function
}

#[cfg(test)]
mod tests {
    use super::*;

    fn modules(names: &[&str]) -> Vec<String> {
        names.iter().map(|name| (*name).to_owned()).collect()
    }

    #[test]
    fn a_new_index_lists_every_migration() {
        let index = render(None, &modules(&["m1_a", "m2_b"]), ProjectOrmBackend::Sqlx).unwrap();
        assert_eq!(
            index,
            format!(
                "{HEADER}\n\npub mod m1_a;\npub mod m2_b;\n\npub fn get_migrations() -> Vec<Box<dyn rullst::db::schema::Migration>> {{\n    vec![\n        Box::new(m1_a::MigrationImpl),\n        Box::new(m2_b::MigrationImpl),\n    ]\n}}\n"
            )
        );
        syn::parse_file(&index).unwrap();
    }

    #[test]
    fn project_modules_and_comments_survive_a_new_migration() {
        // The layout a generated index had once the project added its seeds.
        let existing = "// Generated by Rullst. Do not edit manually.\n\npub mod m20260101000000_create_users_table;\n\n/// Demonstration data.\npub mod demo;\npub mod seeds;\n\npub fn get_migrations() -> Vec<Box<dyn rullst::db::schema::Migration>> {\n    vec![\n        Box::new(m20260101000000_create_users_table::MigrationImpl),\n    ]\n}\n\n#[cfg(test)]\nmod tests {}\n";
        let index = render(
            Some(existing),
            &modules(&[
                "m20260101000000_create_users_table",
                "m20261101000000_create_user_mfa_factors_table",
            ]),
            ProjectOrmBackend::Sqlx,
        )
        .unwrap();
        assert_eq!(
            index,
            format!(
                "{HEADER}\n\npub mod m20260101000000_create_users_table;\npub mod m20261101000000_create_user_mfa_factors_table;\n\n/// Demonstration data.\npub mod demo;\npub mod seeds;\n\npub fn get_migrations() -> Vec<Box<dyn rullst::db::schema::Migration>> {{\n    vec![\n        Box::new(m20260101000000_create_users_table::MigrationImpl),\n        Box::new(m20261101000000_create_user_mfa_factors_table::MigrationImpl),\n    ]\n}}\n\n#[cfg(test)]\nmod tests {{}}\n"
            )
        );
        // Regenerating again changes nothing.
        let again = render(
            Some(&index),
            &modules(&[
                "m20260101000000_create_users_table",
                "m20261101000000_create_user_mfa_factors_table",
            ]),
            ProjectOrmBackend::Sqlx,
        )
        .unwrap();
        assert_eq!(again, index);
    }

    #[test]
    fn a_deleted_migration_is_dropped_and_a_missing_function_appended() {
        let existing = "pub mod seeds;\npub mod m1_gone;\n";
        let index = render(
            Some(existing),
            &modules(&["m2_new"]),
            ProjectOrmBackend::Turso,
        )
        .unwrap();
        assert_eq!(
            index,
            "pub mod seeds;\npub mod m2_new;\n\npub fn get_migrations() -> Result<\n    Vec<rullst_orm::polyglot::TursoMigration>,\n    rullst_orm::polyglot::PolyglotError,\n> {\n    Ok(vec![\n        m2_new::migration()?,\n    ])\n}\n"
        );
        assert!(!index.contains("m1_gone"));
        // Without a trailing newline the function still starts its own line.
        let index = render(Some("pub mod seeds;"), &[], ProjectOrmBackend::Sqlx).unwrap();
        assert!(
            index.starts_with("pub mod seeds;\n\npub fn get_migrations()"),
            "{index}"
        );
    }

    #[test]
    fn an_index_that_does_not_parse_is_left_unchanged() {
        let error = render(Some("pub mod seeds"), &[], ProjectOrmBackend::Sqlx).unwrap_err();
        assert_eq!(error.kind(), io::ErrorKind::InvalidData);
        assert!(error.to_string().contains("left unchanged"), "{error}");
    }

    #[test]
    fn only_migration_shaped_names_count_as_stale_declarations() {
        let ident = |name: &str| syn::Ident::new(name, proc_macro2::Span::call_site());
        assert!(is_migration(&ident("m20260101000000_old"), &[]));
        assert!(is_migration(
            &ident("maintenance"),
            &modules(&["maintenance"])
        ));
        assert!(!is_migration(&ident("maintenance"), &[]));
        assert!(!is_migration(&ident("m"), &[]));
        assert!(!is_migration(&ident("seeds"), &[]));
    }
}

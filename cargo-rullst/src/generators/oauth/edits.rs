type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;

/// The password login route whose position the provider routes follow.
const LOGIN_ROUTE: &str = "rullst::routing::post(controllers::auth_controller::login_submit).layer(rullst::server::from_fn(controllers::auth_controller::credential_rate_limit))";

/// Adds `pub mod <module>;` to `path`, creating the file when missing.
pub(super) fn register_module(path: &Path, module: &str) -> Result<Edit> {
    if !path.try_exists()? {
        return Ok(Edit::create(
            path.to_path_buf(),
            format!("pub mod {module};\n"),
        )?);
    }
    let source = writes::read(path)?;
    let declared = syn::parse_file(&source)?
        .items
        .iter()
        .any(|item| matches!(item, Item::Mod(declared) if declared.ident == module));
    if declared {
        return Err(
            invalid("the module is already declared; integrate the provider manually").into(),
        );
    }
    let mut updated = source.clone();
    if !updated.is_empty() && !updated.ends_with('\n') {
        updated.push('\n');
    }
    updated.push_str(&format!("pub mod {module};\n"));
    Ok(Edit::replace(path.to_path_buf(), source, updated))
}

/// `src/migrations/mod.rs` listing every migration plus `added`, in the
/// layout `cargo rullst make:migration` writes.
pub(super) fn migrations_mod(directory: &Path, added: &str) -> Result<Edit> {
    let path = directory.join("mod.rs");
    let source = writes::read(&path)?;
    let mut modules = vec![added.to_owned()];
    for entry in fs::read_dir(directory)? {
        let entry = entry?.path();
        let stem = entry.file_stem().and_then(|stem| stem.to_str());
        if entry.extension().is_some_and(|extension| extension == "rs")
            && let Some(stem) = stem
            && stem != "mod"
            && stem.starts_with('m')
        {
            if !super::super::is_valid_rust_identifier(stem) {
                return Err(invalid("a migration file name is not a valid module name").into());
            }
            modules.push(stem.to_owned());
        }
    }
    modules.sort();
    let mut updated = String::from("// Generated by Rullst. Do not edit manually.\n\n");
    for module in &modules {
        updated.push_str(&format!("pub mod {module};\n"));
    }
    updated.push_str(
        "\npub fn get_migrations() -> Vec<Box<dyn rullst::db::schema::Migration>> {\n    vec![\n",
    );
    for module in &modules {
        updated.push_str(&format!("        Box::new({module}::MigrationImpl),\n"));
    }
    updated.push_str("    ]\n}\n");
    Ok(Edit::replace(path, source, updated))
}

/// The `rullst` features of the provider and challenge store, plus an
/// application feature `oauth-mock` for offline development.
pub(super) fn manifest(path: &Path, database: Database) -> Result<Edit> {
    let source = writes::read(path)?;
    let with_features =
        crate::generators::chat::ensure_rullst_features(&source, &["oauth", database.feature()])?;
    let mut document = with_features.parse::<DocumentMut>()?;
    if document.get("features").is_none() {
        document["features"] = TomlItem::Table(Table::new());
    }
    let features = document["features"]
        .as_table_mut()
        .ok_or_else(|| invalid("[features] in Cargo.toml is not a table"))?;
    if !features.contains_key("oauth-mock") {
        let mut mock = Array::new();
        mock.push("rullst/oauth-mock");
        features["oauth-mock"] = value(mock);
    }
    Ok(Edit::replace(
        path.to_path_buf(),
        source,
        document.to_string(),
    ))
}

/// Finds the `.route("/login", <password login>)` call of the router.
struct LoginRoute {
    expected: String,
    ends: Vec<usize>,
}

impl<'ast> Visit<'ast> for LoginRoute {
    fn visit_expr_method_call(&mut self, node: &'ast ExprMethodCall) {
        if node.method == "route"
            && node.args.len() == 2
            && let Some(Expr::Lit(path)) = node.args.first()
            && let Lit::Str(path) = &path.lit
            && path.value() == "/login"
            && node
                .args
                .last()
                .is_some_and(|handler| call_tokens(handler) == self.expected)
        {
            self.ends.push(node.span().byte_range().end);
        }
        syn::visit::visit_expr_method_call(self, node);
    }
}

/// Mounts the provider routes after the password login route and reads the
/// provider settings at the start of `router()`, in a recognized starter
/// router (`src/lib.rs`, else `src/main.rs`). `None` when the router is not
/// recognized or already names the routes.
pub(super) fn router(root: &Path, provider: &ProviderSpec) -> Result<Option<Edit>> {
    let path = ["src/lib.rs", "src/main.rs"]
        .into_iter()
        .map(|relative| root.join(relative))
        .find(|path| writes::read(path).is_ok_and(|source| source.contains("fn router(")));
    let Some(path) = path else {
        return Ok(None);
    };
    let source = writes::read(&path)?;
    let name = provider.name;
    if source.contains(&format!("\"/auth/{name}")) {
        return Ok(None);
    }
    let file = syn::parse_file(&source)?;
    let mut visitor = LoginRoute {
        expected: call_tokens(&syn::parse_str::<Expr>(LOGIN_ROUTE)?),
        ends: Vec::new(),
    };
    visitor.visit_file(&file);
    let bodies: Vec<usize> = file
        .items
        .iter()
        .filter_map(|item| match item {
            Item::Fn(function) if function.sig.ident == "router" => {
                Some(function.block.brace_token.span.open().byte_range().end)
            }
            _ => None,
        })
        .collect();
    let ([route_end], [body_start]) = (visitor.ends.as_slice(), bodies.as_slice()) else {
        return Ok(None);
    };
    // Apple POSTs the callback; its offline mock returns with a GET.
    let callback = if provider.form_post {
        format!(
            "rullst::routing::post(controllers::oauth::{name}::callback)\n        .get(controllers::oauth::{name}::mock_callback)"
        )
    } else {
        format!("rullst::routing::get(controllers::oauth::{name}::callback)")
    };
    let routes = format!(
        "\n    // Sign-in with {label}: budgeted per client like the password login.\n    .route(\"/auth/{name}\", rullst::routing::get(controllers::oauth::{name}::start)\n        .layer(rullst::server::from_fn(controllers::auth_controller::credential_rate_limit)))\n    .route(\"/auth/{name}/callback\", {callback}\n        .layer(rullst::server::from_fn(controllers::auth_controller::credential_rate_limit)))",
        label = provider.label
    );
    let initialize = format!(
        "\n    // Stops startup on an invalid {label} sign-in configuration.\n    controllers::oauth::{name}::initialize()?;",
        label = provider.label
    );
    let mut updated = source.clone();
    if body_start >= route_end {
        return Ok(None);
    }
    updated.insert_str(*route_end, &routes);
    updated.insert_str(*body_start, &initialize);
    syn::parse_file(&updated)?;
    Ok(Some(Edit::replace(path, source, updated)))
}

/// Adds the provider's login link after the password form of
/// `login_page` in `src/pages/auth.rs`; `None` when the page is not
/// recognized.
pub(super) fn login_page(root: &Path, provider: &ProviderSpec) -> Result<Option<Edit>> {
    let path = root.join("src/pages/auth.rs");
    let source = writes::read(&path)?;
    let call = format!("crate::controllers::oauth::{}::login_link()", provider.name);
    if source.contains(&call) {
        return Ok(None);
    }
    let file = syn::parse_file(&source)?;
    let range = file.items.iter().find_map(|item| match item {
        Item::Fn(function) if function.sig.ident == "login_page" => {
            Some(function.span().byte_range())
        }
        _ => None,
    });
    let Some(range) = range else {
        return Ok(None);
    };
    let body = &source[range.clone()];
    let Some(form) = body.find("action=\"/login\"") else {
        return Ok(None);
    };
    let Some(close) = body[form..].find("</form>") else {
        return Ok(None);
    };
    let at = range.start + form + close + "</form>".len();
    let mut updated = source.clone();
    updated.insert_str(at, &format!("\n        {{{call}}}"));
    syn::parse_file(&updated)?;
    Ok(Some(Edit::replace(path, source, updated)))
}

/// Documents the provider settings in `.env.example`, when the project has one.
pub(super) fn env_example(root: &Path, provider: &ProviderSpec) -> Result<Option<Edit>> {
    let path = root.join(".env.example");
    if !path.try_exists()? {
        return Ok(None);
    }
    let source = writes::read(&path)?;
    let env = provider.env;
    if source.contains(&format!("{env}_CLIENT_ID")) {
        return Ok(None);
    }
    let mut updated = source.clone();
    if !updated.is_empty() && !updated.ends_with('\n') {
        updated.push('\n');
    }
    let settings: String = provider
        .setting_names()
        .iter()
        .map(|setting| format!("{setting}=\n"))
        .collect();
    updated.push_str(&format!(
        "\n# ── Sign in with {label} (cargo rullst make:oauth {name}) ──\n{notes}{settings}# Defaults to RULLST_PUBLIC_ORIGIN followed by /auth/{name}/callback.\n{env}_REDIRECT_URL=\n",
        label = provider.label,
        name = provider.name,
        notes = provider.env_notes,
    ));
    Ok(Some(Edit::replace(path, source, updated)))
}

/// Lists `path` in `[security] csrf_signed_webhook_paths` of `Rullst.toml`
/// (created when missing), for a callback the provider POSTs from its own
/// site; `None` when it is already listed.
pub(super) fn csrf_exemption(root: &Path, path: &str) -> Result<Option<Edit>> {
    let file = root.join("Rullst.toml");
    let comment = "# make:oauth: the identity provider POSTs this callback from its own site,\n# without this site's CSRF token; the handler requires the state of the\n# login challenge that the browser's challenge cookie names instead.\n";
    if !file.try_exists()? {
        let source = format!("[security]\n{comment}csrf_signed_webhook_paths = [\"{path}\"]\n");
        return Ok(Some(Edit::create(file, source)?));
    }
    let source = writes::read(&file)?;
    let mut document = source.parse::<DocumentMut>()?;
    if document.get("security").is_none() {
        document["security"] = TomlItem::Table(Table::new());
    }
    let security = document["security"]
        .as_table_mut()
        .ok_or_else(|| invalid("[security] in Rullst.toml is not a table"))?;
    match security.get_mut("csrf_signed_webhook_paths") {
        None => {
            let mut paths = Array::new();
            paths.push(path);
            security["csrf_signed_webhook_paths"] = value(paths);
            if let Some(mut key) = security.key_mut("csrf_signed_webhook_paths") {
                key.leaf_decor_mut().set_prefix(comment);
            }
        }
        Some(paths) => {
            let paths = paths.as_array_mut().ok_or_else(|| {
                invalid("csrf_signed_webhook_paths in Rullst.toml is not an array")
            })?;
            if paths.iter().any(|listed| listed.as_str() == Some(path)) {
                return Ok(None);
            }
            paths.push(path);
        }
    }
    Ok(Some(Edit::replace(file, source, document.to_string())))
}

/// Tokens of a call chain without trailing argument commas, so formatting
/// does not change the comparison.
fn call_tokens(expression: &Expr) -> String {
    struct WithoutTrailingCommas;
    impl syn::visit_mut::VisitMut for WithoutTrailingCommas {
        fn visit_expr_call_mut(&mut self, node: &mut syn::ExprCall) {
            node.args.pop_punct();
            syn::visit_mut::visit_expr_call_mut(self, node);
        }
        fn visit_expr_method_call_mut(&mut self, node: &mut ExprMethodCall) {
            node.args.pop_punct();
            syn::visit_mut::visit_expr_method_call_mut(self, node);
        }
    }
    let mut expression = expression.clone();
    syn::visit_mut::VisitMut::visit_expr_mut(&mut WithoutTrailingCommas, &mut expression);
    expression.into_token_stream().to_string()
}

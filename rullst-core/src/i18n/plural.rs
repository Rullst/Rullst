//! CLDR cardinal plural rules for the languages Rullst documents.
//!
//! Operands follow CLDR: `i` is the integer part, `v` the number of visible
//! fraction digits (trailing zeros included) and `n` the absolute value.
//! Compact exponents (`1.2M`) are not formatted by Rullst, so `e` is 0.

use super::Decimal;

/// A CLDR plural category, as selected by [`Locale::plural_category`] and
/// written as a key of a plural message in a catalog.
///
/// [`Locale::plural_category`]: super::Locale::plural_category
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum PluralCategory {
    /// `zero` (Arabic 0).
    Zero,
    /// `one`.
    One,
    /// `two` (Arabic and Hebrew 2).
    Two,
    /// `few`.
    Few,
    /// `many`.
    Many,
    /// `other`, which every language has.
    Other,
}

impl PluralCategory {
    /// The CLDR name: `"one"`, `"few"`, `"other"`.
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Zero => "zero",
            Self::One => "one",
            Self::Two => "two",
            Self::Few => "few",
            Self::Many => "many",
            Self::Other => "other",
        }
    }
}

/// How a catalog locale selects plural forms; generated by `catalog!` and
/// mirrored by its compile-time check.
#[doc(hidden)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum __Plural {
    /// `other` only: ja, zh, ko.
    Other,
    /// `one` for `i = 1 and v = 0`: en, de, nl.
    One,
    /// [`One`](Self::One) plus `many` for exact millions: it, pt-PT.
    OneMany,
    /// `one` for `i = 0,1` plus `many` for exact millions: fr, pt.
    ZeroOne,
    /// `one` for `n = 1`: tr.
    ExactOne,
    /// [`ExactOne`](Self::ExactOne) plus `many` for exact millions: es.
    ExactOneMany,
    /// ru, uk.
    EastSlavic,
    /// pl.
    Polish,
    /// cs.
    Czech,
    /// ro.
    Romanian,
    /// ar.
    Arabic,
    /// he.
    Hebrew,
}

impl __Plural {
    /// The rule of a canonical tag's language; Portuguese regions other
    /// than Brazil and Portugal have none, as in the catalog check.
    pub(crate) fn for_tag(tag: &str) -> Option<Self> {
        let mut subtags = tag.split('-');
        let language = subtags.next().unwrap_or_default();
        let region = subtags.find(|subtag| subtag.len() != 4);
        Some(match language {
            "en" | "de" | "nl" => Self::One,
            "it" => Self::OneMany,
            "fr" => Self::ZeroOne,
            "pt" => match region {
                None | Some("BR") => Self::ZeroOne,
                Some("PT") => Self::OneMany,
                Some(_) => return None,
            },
            "tr" => Self::ExactOne,
            "es" => Self::ExactOneMany,
            "ru" | "uk" => Self::EastSlavic,
            "pl" => Self::Polish,
            "cs" => Self::Czech,
            "ro" => Self::Romanian,
            "ar" => Self::Arabic,
            "he" => Self::Hebrew,
            "ja" | "zh" | "ko" => Self::Other,
            _ => return None,
        })
    }

    /// The category of `number`'s absolute value.
    pub(crate) fn category(self, number: Decimal) -> PluralCategory {
        use PluralCategory::{Few, Many, One, Other, Two, Zero};
        let (i, whole) = number.integer_part();
        let v = number.scale();
        // `n = k` holds only for a value without fraction digits other than 0.
        let n_is = |k: u128| whole && i == k;
        let millions = v == 0 && i != 0 && i.is_multiple_of(1_000_000);
        match self {
            Self::Other => Other,
            Self::One | Self::OneMany if i == 1 && v == 0 => One,
            Self::ZeroOne if i <= 1 => One,
            Self::ExactOne | Self::ExactOneMany if n_is(1) => One,
            Self::OneMany | Self::ZeroOne | Self::ExactOneMany if millions => Many,
            Self::One | Self::OneMany | Self::ZeroOne | Self::ExactOne | Self::ExactOneMany => {
                Other
            }
            Self::EastSlavic | Self::Polish if v != 0 => Other,
            Self::EastSlavic if i % 10 == 1 && i % 100 != 11 => One,
            Self::Polish if i == 1 => One,
            Self::EastSlavic | Self::Polish => {
                if (2..=4).contains(&(i % 10)) && !(12..=14).contains(&(i % 100)) {
                    Few
                } else {
                    Many
                }
            }
            Self::Czech if v != 0 => Many,
            Self::Czech if i == 1 => One,
            Self::Czech if (2..=4).contains(&i) => Few,
            Self::Czech => Other,
            Self::Romanian if i == 1 && v == 0 => One,
            Self::Romanian if v != 0 || i == 0 || (1..=19).contains(&(i % 100)) => Few,
            Self::Romanian => Other,
            Self::Arabic if !whole => Other,
            Self::Arabic if i == 0 => Zero,
            Self::Arabic if i == 1 => One,
            Self::Arabic if i == 2 => Two,
            Self::Arabic if (3..=10).contains(&(i % 100)) => Few,
            Self::Arabic if (11..=99).contains(&(i % 100)) => Many,
            Self::Arabic => Other,
            Self::Hebrew if (i == 1 && v == 0) || (i == 0 && v != 0) => One,
            Self::Hebrew if i == 2 && v == 0 => Two,
            Self::Hebrew => Other,
        }
    }
}

